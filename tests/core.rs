use qwen_rust::{ops, quant, sampling::Sampler};

#[test]
fn routing_uses_topk_and_renormalizes() {
    let selected = ops::route(&[1., 3., 2., -10.], 2).unwrap();
    assert_eq!(selected[0].0, 1);
    assert_eq!(selected[1].0, 2);
    assert!((selected.iter().map(|v| v.1).sum::<f32>() - 1.).abs() < 1e-6);
    assert!((selected[0].1 - 0.7310586).abs() < 1e-6);
    assert!(ops::route(&[f32::NAN], 1).is_err());
    assert!(ops::route(&[1.], 0).is_err());
}
#[test]
fn neox_rotates_split_halves() {
    let mut x = vec![1., 2., 3., 4.];
    ops::rope(&mut x, 4, 1, 10000.);
    assert!((x[0] - (1f32.cos() - 3. * 1f32.sin())).abs() < 1e-6);
    assert!((x[1] - (2. * 0.01f32.cos() - 4. * 0.01f32.sin())).abs() < 1e-6);
}
#[test]
fn gqa_maps_contiguous_query_heads() {
    let q = vec![0.; 8];
    let k = vec![0.; 8];
    let v = vec![2., 4., 10., 20., 6., 8., 30., 40.];
    let out = ops::attention(&q, &k, &v, 4, 2, 2).unwrap();
    assert_eq!(out, vec![4., 6., 4., 6., 20., 30., 20., 30.]);
}
#[test]
fn sampler_seed_and_greedy() {
    let mut s = Sampler::new(42, 0., 0, 1.).unwrap();
    assert_eq!(s.sample(&[0., 4., 2.]).unwrap(), 1);
    assert!(s.sample(&[f32::NAN]).is_err());
    assert!(Sampler::new(1, 1., 1, 0.).is_err());
    let mut a = Sampler::new(77, 1., 0, 1.).unwrap();
    let mut b = Sampler::new(77, 1., 0, 1.).unwrap();
    for _ in 0..40 {
        assert_eq!(
            a.sample(&[1., 2., 3.]).unwrap(),
            b.sample(&[1., 2., 3.]).unwrap()
        );
    }
}

#[test]
fn sampler_topk_matches_full_sort_distribution() {
    // Compare the optimized partial selection against the old full-sort CDF.
    use rand::{rngs::StdRng, Rng, SeedableRng};
    let logits: Vec<f32> = (0..1000).map(|i| ((i * 97) % 31) as f32 / 11.).collect();
    for top in [0, 1, 20, 999, 1000, 2000] {
        let mut sampler = Sampler::new(123, 0.7, top, 0.8).unwrap();
        let mut rng = StdRng::seed_from_u64(123);
        let mut ids: Vec<usize> = (0..logits.len()).collect();
        ids.sort_by(|&a, &b| logits[b].total_cmp(&logits[a]).then(a.cmp(&b)));
        if top > 0 {
            ids.truncate(top.min(ids.len()));
        }
        let mut probs: Vec<f32> = ids
            .iter()
            .map(|&i| ((logits[i] - logits[ids[0]]) / 0.7).exp())
            .collect();
        let total: f32 = probs.iter().sum();
        let mut cumulative = 0.;
        let mut len = probs.len();
        for (i, &p) in probs.iter().enumerate() {
            cumulative += p / total;
            if cumulative >= 0.8 {
                len = i + 1;
                break;
            }
        }
        probs.truncate(len);
        ids.truncate(len);
        let total: f32 = probs.iter().sum();
        for _ in 0..40 {
            let mut draw = rng.gen::<f32>() * total;
            let mut expected = *ids.last().unwrap();
            for (&id, &prob) in ids.iter().zip(&probs) {
                if draw < prob {
                    expected = id;
                    break;
                }
                draw -= prob;
            }
            assert_eq!(
                sampler.sample(&logits).unwrap(),
                expected as u32,
                "top={top}"
            );
        }
    }
    let mut sampler = Sampler::new(0, 0., 0, 1.).unwrap();
    assert_eq!(sampler.sample(&[1., 1., 0.]).unwrap(), 0);
}
#[test]
fn reject_bad_quant_shapes() {
    assert!(quant::row_bytes(12, 255).is_err());
    assert!(quant::row_bytes(99, 256).is_err());
    assert!(quant::decode(&[], 14, 256).is_err());
}

fn fixture(kind: u32) -> (Vec<u8>, Vec<f32>) {
    // Nonuniform packed scale/high-bit data. Expected values generated by separate
    // block-wise reference equations below, not by quant::value.
    let (n, size) = quant::layout(kind).unwrap();
    let mut b = vec![0u8; size * 2];
    let mut expected = Vec::new();
    for block in 0..2 {
        let p = block * size;
        for j in 0..size {
            b[p + j] = ((j * 73 + block * 29 + 19) % 256) as u8;
        }
        match kind {
            0 => {
                let f = if block == 0 { 0.75f32 } else { -1.25 };
                b[p..p + 4].copy_from_slice(&f.to_le_bytes());
                expected.push(f);
            }
            1 => {
                let f = if block == 0 { 0.75f32 } else { -1.25 };
                b[p..p + 2].copy_from_slice(&half::f16::from_f32(f).to_bits().to_le_bytes());
                expected.push(f);
            }
            2 | 8 => {
                b[p..p + 2].copy_from_slice(&half::f16::from_f32(0.125).to_bits().to_le_bytes());
                if kind == 8 {
                    expected.extend(b[p + 2..p + 34].iter().map(|&v| v as i8 as f32 * 0.125));
                } else {
                    for shift in [0, 4] {
                        expected.extend(
                            b[p + 2..p + 18]
                                .iter()
                                .map(|&v| (((v >> shift) & 15) as i32 - 8) as f32 * 0.125),
                        );
                    }
                }
            }
            12 | 13 => {
                b[p..p + 2].copy_from_slice(&half::f16::from_f32(0.125).to_bits().to_le_bytes());
                b[p + 2..p + 4]
                    .copy_from_slice(&half::f16::from_f32(0.0625).to_bits().to_le_bytes());
                // Build explicit 6-bit scale arrays from serialized chunks.
                let packed = &b[p + 4..p + 16];
                let mut ds = [0u8; 8];
                let mut ms = [0u8; 8];
                for j in 0..4 {
                    ds[j] = packed[j] & 63;
                    ms[j] = packed[j + 4] & 63;
                    ds[j + 4] = (packed[j + 8] & 15) | ((packed[j] >> 6) * 16);
                    ms[j + 4] = (packed[j + 8] >> 4) | ((packed[j + 4] >> 6) * 16);
                }
                for chunk in 0..4 {
                    for upper in 0..2 {
                        for lane in 0..32 {
                            let qs = p + if kind == 12 { 16 } else { 48 };
                            let mut q = (b[qs + chunk * 32 + lane] >> (upper * 4)) & 15;
                            let g = chunk * 2 + upper;
                            if kind == 13 && ((b[p + 16 + lane] >> g) & 1) != 0 {
                                q += 16;
                            }
                            expected.push(0.125 * ds[g] as f32 * q as f32 - 0.0625 * ms[g] as f32);
                        }
                    }
                }
            }
            14 => {
                b[p + 208..p + 210]
                    .copy_from_slice(&half::f16::from_f32(0.125).to_bits().to_le_bytes());
                let mut out = [0.; 256];
                for chunk in 0..2 {
                    for lane in 0..32 {
                        let low0 = b[p + chunk * 64 + lane];
                        let low1 = b[p + chunk * 64 + 32 + lane];
                        let hi = b[p + 128 + chunk * 32 + lane];
                        let qs = [
                            (low0 & 15) | ((hi & 3) << 4),
                            (low1 & 15) | (((hi >> 2) & 3) << 4),
                            (low0 >> 4) | (((hi >> 4) & 3) << 4),
                            (low1 >> 4) | (((hi >> 6) & 3) << 4),
                        ];
                        for quarter in 0..4 {
                            out[chunk * 128 + quarter * 32 + lane] = 0.125
                                * (b[p + 192 + chunk * 8 + quarter * 2 + lane / 16] as i8) as f32
                                * (qs[quarter] as i32 - 32) as f32;
                        }
                    }
                }
                expected.extend(out);
            }
            _ => unreachable!(),
        }
    }
    assert_eq!(expected.len(), n * 2);
    (b, expected)
}
#[test]
fn quantized_blocks_match_known_layouts() {
    for kind in [0, 1, 2, 8, 12, 13, 14] {
        let (b, expected) = fixture(kind);
        let actual = quant::decode(&b, kind, expected.len()).unwrap();
        assert_eq!(actual, expected, "kind={kind}");
    }
}
#[test]
#[ignore = "requires Vulkan; enable with --ignored; software must be explicit"]
fn vulkan_quantized_matvec_and_cache() {
    let allow = std::env::var("QWEN_TEST_ALLOW_SOFTWARE").as_deref() == Ok("1");
    let mut gpu = qwen_rust::backend::Vulkan::new(1, None, allow).unwrap();
    for kind in [0, 1, 2, 8, 12, 13, 14] {
        let (b, decoded) = fixture(kind);
        let cols = decoded.len();
        let x: Vec<f32> = (0..cols).map(|i| ((i % 13) as f32 - 6.) / 7.).collect();
        let expected: f32 = x.iter().zip(decoded).map(|(a, b)| a * b).sum();
        let mut bytes = Vec::new();
        for _ in 0..3 {
            bytes.extend_from_slice(&b);
        }
        for _ in 0..2 {
            let actual = gpu
                .packed_matvec(
                    (kind as usize + 100, bytes.len()),
                    &bytes,
                    kind,
                    3,
                    cols,
                    &x,
                )
                .unwrap();
            for y in actual {
                assert!(
                    (y - expected).abs() < 0.002 + expected.abs() * 0.00005,
                    "kind={kind}: {y} vs {expected}"
                );
            }
        }
    }
}
#[test]
#[ignore = "requires Vulkan; verifies the vocabulary-size dispatch grid and LRU eviction"]
fn vulkan_large_grid_and_eviction() {
    let allow = std::env::var("QWEN_TEST_ALLOW_SOFTWARE").as_deref() == Ok("1");
    let mut gpu = qwen_rust::backend::Vulkan::new(1, None, allow).unwrap();
    let rows = 70001;
    let x = [1.5f32, -0.5];
    for (key, scale) in [(10, 1f32), (11, 2.), (12, 3.), (10, 1.)] {
        let mut data = Vec::with_capacity(rows * 8);
        for _ in 0..rows {
            data.extend_from_slice(&scale.to_le_bytes());
            data.extend_from_slice(&(scale * 2.).to_le_bytes());
        }
        let out = gpu
            .packed_matvec((key, data.len()), &data, 0, rows, 2, &x)
            .unwrap();
        assert_eq!(out.len(), rows);
        for v in out {
            assert!((v - scale * 0.5).abs() < 1e-5);
        }
    }
    use qwen_rust::backend::Backend;
    assert_eq!(gpu.stats().cache_hits, 0);
}
